import {Platform} from 'react-native';

/**
 * 기능을 쓰기 전에 로그인을 요구하는지.
 *
 * iOS 는 요구하지 않는다. App Store 심사 지침 5.1.1(v) — 계정 기반 기능이
 * 없는 앱은 로그인 없이 쓸 수 있어야 하고, 특정 소셜 네트워크와 관련 없는
 * 앱이 소셜 로그인만 둘 거면 로그인 없이 쓰는 길을 반드시 열어야 한다.
 * 촬영·앨범·프레임·갤러리는 모두 기기 안에서 돌고 QR 업로드도 계정과
 * 묶이지 않아, 이 사유로 0.1.0 (3) 이 반려됐다.
 *
 * iOS 에서 로그인은 설정에서만 한다. 안드로이드는 아직 예전처럼 게이트를
 * 둔다 — 정책을 맞출지는 따로 정한다.
 *
 * 나중에 계정 기반 기능(예: 프레임을 서버에 저장해 다른 기기에서 쓰기)이
 * 생기면 그 기능에만 다시 로그인을 걸 수 있다. 유료 기능은 로그인을 조건으로
 * 걸 수 없다(5.1.1(ii)).
 */
export const LOGIN_REQUIRED = Platform.OS !== 'ios';
